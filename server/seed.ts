async function seed() {
  try {
    await pool.query('DELETE FROM tasks');
    console.log('Cleared existing tasks');

    for (const task of tasks) {
      await pool.query(
        `INSERT INTO tasks (phase, phase_order, title, description, details, status, sort_order)
         VALUES ($1, $2, $3, $4, $5, 'pending', $6)`,
        [task.phase, task.phase_order, task.title, task.description, task.details, task.sort_order]
      );
    }

    console.log(`Seeded ${tasks.length} tasks`);

    const result = await pool.query('SELECT COUNT(*) FROM tasks');
    console.log(`Total tasks in DB: ${result.rows[0].count}`);
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : String(err);
    console.error('Seed failed:', message);
    process.exit(1);
  } finally {
    await pool.end();
  }
}

seed();
